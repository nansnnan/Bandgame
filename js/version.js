  /* 版本规则：1-5 项 → 末位 +1；6-10 项 → 中位 +1 并清空末位；11 项以上 → 首位 +1 并清空后两位。各段数字不进位。 */
  function bumpVersion(version, count) {
    const parts = String(version).split('.').map(n => parseInt(n, 10) || 0);
    while (parts.length < 3) parts.push(0);
    if (count >= 11) {
      parts[0] += 1;
      parts[1] = 0;
      parts[2] = 0;
    } else if (count >= 6) {
      parts[1] += 1;
      parts[2] = 0;
    } else {
      parts[2] += 1;
    }
    return parts.join('.');
  }

